import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const origin = process.env.WISHIX_TEST_ORIGIN || 'http://127.0.0.1:5193'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  for (const locale of ['en', 'ru', 'ro']) for (const width of [320, 390, 768, 1024, 1440]) {
    const context = await browser.newContext({ locale, viewport: { width, height: 900 } })
    const page = await context.newPage()
    let googleRequests = 0
    await page.route('**/googletagmanager.com/**', route => { googleRequests++; return route.fulfill({ contentType: 'text/javascript', body: '' }) })
    await page.route('**/api/auth/me', route => route.fulfill({ json: { user: null } }))
    await page.goto(origin + '/')
    await page.locator('.cookie-panel').waitFor()
    assert.equal(await page.locator('.site-footer a[href="/login"]').count(), 0, 'footer never offers sign-in')
    assert.equal(await page.locator('.site-footer .footer-brand img').count(), 1, 'footer has the Wishix logo')
    assert.equal(googleRequests, 0, 'no Google request before consent')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false, locale + '/' + width + ' overflow')
    const offscreen = await page.locator('.cookie-panel button').evaluateAll(elements => elements.some(el => { const r=el.getBoundingClientRect(); return r.left < 0 || r.right > innerWidth || r.width < 44 || r.height < 44 }))
    assert.equal(offscreen, false, locale + '/' + width + ' controls must fit')
    assert.equal(await page.locator('.cookie-actions button').count(), 2, 'initial panel has accept and settings')
    await page.locator('.cookie-actions button').nth(1).click()
    assert.equal(await page.locator('.cookie-option input').isChecked(), true, 'analytics is selected initially')
    assert.equal(googleRequests, 0, 'a preselected option must not start Google before saving')
    await page.locator('.cookie-option input').uncheck()
    await page.locator('.cookie-actions button').nth(1).click()
    await page.reload()
    assert.equal(await page.locator('.cookie-panel').count(), 0, 'choice remembered')
    assert.equal(googleRequests, 0, 'no Google request after denial')
    await page.locator('footer .cookie-settings-link').click()
    assert.equal(await page.locator('.cookie-panel').evaluate(element => document.activeElement === element), true, 'focus moves into reopened settings')
    assert.equal(await page.locator('.cookie-option input').isChecked(), false, 'saved denial remains unchecked')
    await page.locator('.cookie-actions button').first().click()
    await page.waitForFunction(() => window.dataLayer?.length >= 3)
    const queued = await page.evaluate(() => window.dataLayer.map(x => [...x]))
    const view = queued.find(x => x[0] === 'event' && x[1] === 'page_view')
    assert.equal(view[2].page_title, 'home')
    assert.ok(view[2].page_location.endsWith('/analytics/home'))
    await page.locator('footer .cookie-settings-link').click()
    assert.equal(await page.locator('.cookie-option input').isChecked(), true, 'accept all enabled analytics')
    await page.locator('.cookie-option input').uncheck()
    await page.locator('.cookie-actions button').nth(1).click()
    await page.waitForLoadState('domcontentloaded')
    assert.equal(await page.evaluate(() => localStorage.getItem('wishix_analytics_consent_v1')), 'denied')
    await context.close()
  }
  const context = await browser.newContext()
  const page = await context.newPage()
  let googleRequests = 0
  await page.route('**/googletagmanager.com/**', route => { googleRequests++; return route.fulfill({ contentType:'text/javascript', body:'' }) })
  await page.route('**/api/auth/me', route => route.fulfill({ json: { user: null } }))
  await page.goto(origin + '/')
  await page.evaluate(() => history.replaceState(null, '', '/u/person/wishlist/list-id/fake-token?email=fake@example.test'))
  await page.locator('.cookie-actions button').first().click()
  const queued = await page.evaluate(() => window.dataLayer.map(x => [...x]))
  const sent = JSON.stringify(queued)
  assert.ok(sent.includes('/analytics/shared_list'))
  assert.ok(!sent.includes('fake-token') && !sent.includes('fake@example.test') && !sent.includes('list-id'))
  await page.goto(origin + '/reservation?token=super-secret')
  assert.equal(await page.evaluate(() => !!window.gtag), false, 'do not load Google on reservation management page')
  const count = googleRequests
  await page.waitForTimeout(200)
  assert.equal(googleRequests, count)
  await context.close()
  const shopContext = await browser.newContext()
  const shopPage = await shopContext.newPage()
  await shopPage.route('**/googletagmanager.com/**', route => route.fulfill({ contentType:'text/javascript', body:'' }))
  await shopPage.route('**/api/auth/me', route => route.fulfill({ json: { user: { username:'tester', email:'test@example.com' } } }))
  await shopPage.route('**/api/wishes', route => route.fulfill({ json: { wishes: [{ id:'wish-1', title:'Example', priority:'medium', price:null, currency:'', image_url:null, description:'', shop_links:['https://shop.example/product?code=918273'] }] } }))
  await shopPage.goto(origin + '/my/wishes')
  await shopPage.locator('.cookie-actions button').first().click()
  const shopLink = shopPage.locator('.shop-links a')
  await shopLink.waitFor()
  await shopLink.evaluate(link => { link.addEventListener('click', event => event.preventDefault()); link.click() })
  const shopEvents = await shopPage.evaluate(() => window.dataLayer.map(item => [...item]).filter(item => item[0] === 'event' && item[1] === 'shop_link_opened'))
  assert.equal(shopEvents.length, 1, 'record a shop click')
  assert.ok(!JSON.stringify(shopEvents).includes('918273'), 'do not pass shop URL to analytics')
  await shopContext.close()
  const searchContext = await browser.newContext()
  const searchPage = await searchContext.newPage()
  await searchPage.route('**/googletagmanager.com/**', route => route.fulfill({ contentType:'text/javascript', body:'' }))
  await searchPage.route('**/api/auth/me', route => route.fulfill({ json: { user: { username:'tester', email:'test@example.com' } } }))
  await searchPage.route('**/api/search/people?*', route => route.fulfill({ json: { people: [], next_cursor: '' } }))
  await searchPage.goto(origin + '/my/search')
  await searchPage.locator('.cookie-actions button').first().click()
  await searchPage.locator('#people-search').fill('sample-private-query')
  await searchPage.locator('.search-form button').click()
  await searchPage.locator('.search-empty').waitFor()
  const searches = await searchPage.evaluate(() => window.dataLayer.map(item => [...item]).filter(item => item[0] === 'event' && item[1] === 'people_search_completed'))
  assert.equal(searches.length, 1, 'record one successful search')
  assert.ok(!JSON.stringify(searches).includes('sample-private-query'), 'do not pass the search text')
  await searchContext.close()
  const publicFooterTexts = []
  for (const user of [null, { username:'tester', email:'test@example.com' }]) {
    const footerContext = await browser.newContext({ locale:'ru' })
    const footerPage = await footerContext.newPage()
    await footerPage.addInitScript(() => localStorage.setItem('wishix_analytics_consent_v1', 'denied'))
    await footerPage.route('**/api/auth/me', route => route.fulfill({ json: { user } }))
    await footerPage.goto(origin + '/')
    publicFooterTexts.push(await footerPage.locator('.site-footer').innerText())
    await footerContext.close()
  }
  assert.equal(publicFooterTexts[0], publicFooterTexts[1], 'footer content is independent of sign-in state')
  for (const width of [320, 390, 768, 1024, 1440]) {
    const privateContext = await browser.newContext({ locale:'ru', viewport:{ width, height:900 } })
    const privatePage = await privateContext.newPage()
    await privatePage.addInitScript(() => localStorage.setItem('wishix_analytics_consent_v1', 'granted'))
    await privatePage.route('**/googletagmanager.com/**', route => route.fulfill({ contentType:'text/javascript', body:'' }))
    await privatePage.route('**/api/auth/me', route => route.fulfill({ json: { user: { username:'tester', email:'test@example.com' } } }))
    await privatePage.route('**/api/lists', route => route.fulfill({ json: { lists: [] } }))
    await privatePage.route('**/api/wishes', route => route.fulfill({ json: { wishes: [] } }))
    await privatePage.goto(origin + '/my')
    const footerLink = privatePage.locator('.site-footer .cookie-settings-link')
    await footerLink.waitFor()
    assert.equal(await privatePage.locator('.site-footer a[href="/login"]').count(), 0, 'private footer has no sign-in link')
    assert.equal(await privatePage.locator('.site-footer .footer-brand img').count(), 1, 'private footer uses the same brand')
    await privatePage.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
    const geometry = await footerLink.evaluate(element => {
      const link = element.getBoundingClientRect()
      const nav = document.querySelector('.bottom-navigation')
      const navVisible = nav && getComputedStyle(nav).display !== 'none'
      return { overflow: document.documentElement.scrollWidth > document.documentElement.clientWidth, overlap: navVisible && link.bottom > nav.getBoundingClientRect().top, height: link.height }
    })
    assert.equal(geometry.overflow, false, width + ' private footer overflow')
    assert.equal(geometry.overlap, false, width + ' footer link is covered by navigation')
    assert.ok(geometry.height >= 44, width + ' footer touch target')
    await footerLink.click()
    assert.equal(await privatePage.locator('.cookie-option input').isChecked(), true)
    await privateContext.close()
  }
  console.log('Passed: consent, withdrawal, sanitized page view, reservation management, EN/RU/RO and five widths.')
} finally { await browser.close() }
