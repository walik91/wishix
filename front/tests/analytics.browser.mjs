import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const origin = process.env.WISHIX_TEST_ORIGIN || 'http://127.0.0.1:5193'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  for (const locale of ['en', 'ru', 'ro']) for (const width of [320, 390, 768, 1024, 1440]) {
    const context = await browser.newContext({ locale, viewport: { width, height: 900 } })
    const page = await context.newPage()
    let googleRequests = 0
    await page.route('**/googletagmanager.com/**', route => { googleRequests++; return route.fulfill({ contentType: 'text/javascript', body: '' }) })
    await page.route('**/api/auth/me', route => route.fulfill({ json: { user: null } }))
    await page.goto(origin + '/')
    await page.locator('.cookie-panel').waitFor()
    assert.equal(googleRequests, 0, 'no Google request before consent')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth), false, locale + '/' + width + ' overflow')
    const offscreen = await page.locator('.cookie-panel button').evaluateAll(elements => elements.some(el => { const r=el.getBoundingClientRect(); return r.left < 0 || r.right > innerWidth || r.width < 44 || r.height < 44 }))
    assert.equal(offscreen, false, locale + '/' + width + ' controls must fit')
    await page.locator('.cookie-actions button').nth(1).click()
    await page.reload()
    assert.equal(await page.locator('.cookie-panel').count(), 0, 'choice remembered')
    assert.equal(googleRequests, 0, 'no Google request after denial')
    await page.locator('.cookie-settings').click()
    await page.locator('.cookie-option input').check()
    await page.locator('.cookie-actions button').first().click()
    await page.waitForFunction(() => window.dataLayer?.length >= 3)
    const queued = await page.evaluate(() => window.dataLayer.map(x => [...x]))
    const view = queued.find(x => x[0] === 'event' && x[1] === 'page_view')
    assert.equal(view[2].page_title, 'home')
    assert.ok(view[2].page_location.endsWith('/analytics/home'))
    await page.locator('.cookie-settings').click()
    await page.locator('.cookie-actions button').nth(1).click()
    await page.waitForLoadState('domcontentloaded')
    assert.equal(await page.evaluate(() => localStorage.getItem('wishix_analytics_consent_v1')), 'denied')
    await context.close()
  }
  const context = await browser.newContext()
  const page = await context.newPage()
  let googleRequests = 0
  await page.route('**/googletagmanager.com/**', route => { googleRequests++; return route.fulfill({ contentType:'text/javascript', body:'' }) })
  await page.route('**/api/auth/me', route => route.fulfill({ json: { user: null } }))
  await page.goto(origin + '/')
  await page.evaluate(() => history.replaceState(null, '', '/u/person/wishlist/list-id/fake-token?email=fake@example.test'))
  await page.locator('.cookie-actions button').first().click()
  const queued = await page.evaluate(() => window.dataLayer.map(x => [...x]))
  const sent = JSON.stringify(queued)
  assert.ok(sent.includes('/analytics/shared_list'))
  assert.ok(!sent.includes('fake-token') && !sent.includes('fake@example.test') && !sent.includes('list-id'))
  await page.goto(origin + '/reservation?token=super-secret')
  assert.equal(await page.evaluate(() => !!window.gtag), false, 'do not load Google on reservation management page')
  const count = googleRequests
  await page.waitForTimeout(200)
  assert.equal(googleRequests, count)
  await context.close()
  console.log('Passed: consent, withdrawal, sanitized page view, reservation management, EN/RU/RO and five widths.')
} finally { await browser.close() }
