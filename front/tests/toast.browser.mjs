import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const origin = process.env.WISHIX_TEST_ORIGIN || 'http://localhost:5174'
const texts = Object.fromEntries(await Promise.all(['en', 'ru', 'ro'].map(async lang => [lang, JSON.parse(await readFile(new URL(`../src/locales/${lang}.json`, import.meta.url)))])))
const id = '00000000-0000-4000-8000-000000000001', token = 'a'.repeat(43)
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
try {
  await mkdir(new URL('../../.cache/toast-screens/', import.meta.url), { recursive: true })
  for (const lang of ['en', 'ru', 'ro']) for (const width of [320, 390, 768, 1024, 1440]) {
    const context = await browser.newContext({ locale: lang, viewport: { width, height: 844 } })
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.message))
    page.on('console', message => { if (message.text().includes('[Vue warn]')) errors.push(message.text()) })
    await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { if (window.failClipboard) throw new Error('unavailable') } } }))
    await page.route('**/api/auth/me', route => route.fulfill({ json: { user: { username: 'example', email: 'private@example.test' } } }))
    await page.route(`**/api/lists/${id}`, route => route.fulfill({ json: { list: { id, title: 'Birthday', description: '', event_date: null, visibility: 'link', wish_count: 0, revision: 1, share_path: `/${id}/${token}` }, wishes: [] } }))
    await page.route('**/api/lists', route => route.fulfill({ json: { lists: [] } }))
    await page.route('**/api/wishes', route => route.fulfill({ json: { wishes: [] } }))
    await page.goto(`${origin}/my/lists/${id}`)
    await page.getByRole('button', { name: texts[lang]['lists.share'], exact: true }).click()
    const dialog = page.getByRole('dialog', { name: texts[lang]['lists.share'], exact: true })
    const copy = dialog.getByRole('button', { name: texts[lang]['lists.copyLink'], exact: true })
    await copy.click()
    const toast = page.getByRole('status').filter({ hasText: texts[lang]['lists.notice.copiedLink'] })
    await toast.waitFor()
    const geometry = await toast.evaluate(element => {
      const box = element.getBoundingClientRect(), top = document.elementFromPoint(box.left + box.width / 2, box.top + box.height / 2)
      return { x: box.x, y: box.y, width: box.width, height: box.height, viewportWidth: document.documentElement.clientWidth, viewportHeight: innerHeight, topmost: element.contains(top), popover: element.matches(':popover-open'), inDialog: !!element.closest('dialog[open]'), overflow: document.documentElement.scrollWidth > document.documentElement.clientWidth }
    })
    assert.equal(geometry.topmost, true, `${lang}/${width}: toast behind dialog`)
    assert.equal(geometry.popover, true, `${lang}/${width}: toast not in top layer`)
    assert.equal(geometry.inDialog, true, `${lang}/${width}: toast outside modal focus scope`)
    assert.equal(geometry.overflow, false, `${lang}/${width}: overflow`)
    assert.ok(geometry.width < width && geometry.y + geometry.height <= geometry.viewportHeight, `${lang}/${width}: invalid geometry`)
    if (width < 1024) assert.ok(Math.abs(geometry.x + geometry.width / 2 - geometry.viewportWidth / 2) < 2, `${lang}/${width}: toast not centered ${JSON.stringify(geometry)}`)
    else assert.ok(geometry.viewportWidth - geometry.x - geometry.width <= 48, `${lang}/${width}: toast not right aligned ${JSON.stringify(geometry)}`)
    if (lang === 'ru' && [390, 1440].includes(width)) await page.screenshot({ path: new URL(`../../.cache/toast-screens/dialog-${width}.png`, import.meta.url).pathname.replace(/^\/(\w:)/, '$1') })
    if (lang === 'en' && width === 390) {
      await page.waitForTimeout(3200)
      await copy.click()
      await page.waitForTimeout(3200)
      assert.equal(await toast.isVisible(), true, 'repeated copy did not restart timer')
      await toast.waitFor({ state: 'detached', timeout: 5000 })
      await page.evaluate(() => { window.failClipboard = true })
      await copy.click()
      const fallback = page.getByRole('status').filter({ hasText: texts[lang]['lists.notice.selectLink'] })
      await fallback.waitFor()
      assert.equal(await page.locator('#list-share-url').evaluate(input => input.selectionStart === 0 && input.selectionEnd === input.value.length), true)
      await page.waitForTimeout(6200)
      assert.equal(await fallback.isVisible(), true, 'manual-copy instructions disappeared')
      await fallback.getByRole('button', { name: texts[lang]['wishes.dismiss'], exact: true }).click()
      await page.evaluate(() => { window.failClipboard = false })
      await copy.click(); await toast.waitFor()
    }
    await toast.getByRole('button', { name: texts[lang]['wishes.dismiss'] }).click()
    await toast.waitFor({ state: 'detached' })
    assert.equal(await dialog.isVisible(), true)
    await copy.click(); await toast.waitFor()
    await dialog.getByRole('button', { name: texts[lang]['my.close'], exact: true }).click()
    await page.waitForFunction(() => !!document.querySelector('.toast:popover-open') && !document.querySelector('.toast')?.closest('dialog'))
    await toast.getByRole('button', { name: texts[lang]['wishes.dismiss'] }).click()
    await page.goto(`${origin}/my/lists?notice=deleted`)
    await page.getByRole('status').filter({ hasText: texts[lang]['lists.notice.deleted'] }).waitFor()
    await context.close()
  }
  assert.deepEqual(errors, [])
  console.log('Toast over modal and page: EN/RU/RO × 320/390/768/1024/1440 passed.')
} finally { await browser.close() }
