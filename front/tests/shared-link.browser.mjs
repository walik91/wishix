import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const origin = process.env.WISHIX_TEST_ORIGIN || 'http://localhost:5173'
const texts = JSON.parse(await readFile(new URL('../src/locales/en.json', import.meta.url)))
const token = 'a'.repeat(43), nextToken = 'b'.repeat(43)
const owner = 'walik', id = '00000000-0000-4000-8000-000000000001'
const list = { id, title: 'Birthday', description: '', event_date: null, visibility: 'link', wish_count: 0, revision: 1, share_path: `/${id}/${token}` }
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const context = await browser.newContext({ locale: 'en' })
const page = await context.newPage(), errors = []
const html = await (await context.request.get(origin)).text()
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.text().includes('[Vue warn]')) errors.push(message.text()) })
await page.route(`**/u/${owner}`, route => route.fulfill({ contentType: 'text/html', body: html }))
await page.route('**/u/*/wishlist/**', async route => {
 if (route.request().resourceType() !== 'document') return route.continue()
 const url = new URL(route.request().url())
 if (url.pathname.startsWith('/u/old_user/')) return route.fulfill({ status: 301, headers: { location: `/u/${owner}/wishlist/${id}/${token}` } })
 return route.fulfill({ status: 200, contentType: 'text/html', body: html })
})
await page.route('**/api/auth/me', route => route.fulfill({ json: { user: { username: owner, email: 'test@example.com' } } }))
await page.route(`**/api/lists/${id}`, route => route.fulfill({ json: { list, wishes: [] } }))
await page.route(`**/api/public/profiles/${owner}`, route => route.fulfill({ json: { username: owner, lists: [{ ...list, visibility: 'public', share_path: `/${id}` }] } }))
await page.route(`**/api/public/profiles/${owner}/details`, route => route.fulfill({ json: { username: owner } }))
await page.route(`**/api/social/${owner}/state`, route => route.fulfill({ json: { self: true } }))
await page.route('**/api/public/lists/guest', route => {
 const body = route.request().postDataJSON()
 return body.id === id && (body.token === token || body.token === '') ? route.fulfill({ json: { username: owner, list: { ...list, visibility: body.token ? 'link' : 'public' }, wishes: [] } }) : route.fulfill({ status: 404, json: { error: 'list_not_found' } })
})
try {
 await page.goto(`${origin}/my/lists/${id}`)
 await page.getByRole('button', { name: texts['lists.share'], exact: true }).click()
 assert.equal(await page.locator('#list-share-url').inputValue(), `${origin}/u/${owner}/wishlist/${id}/${token}`)
 await page.goto(`${origin}/u/${owner}`)
 const card = page.getByRole('link', { name: /Birthday/ })
 await card.waitFor()
 assert.equal(await card.getAttribute('href'), `/u/${owner}/wishlist/${id}`)
 const cardBox = await card.boundingBox()
 await card.click({ position: { x: cardBox.width - 5, y: cardBox.height / 2 } })
 await page.getByRole('heading', { name: 'Birthday', exact: true }).waitFor()
 assert.equal(new URL(page.url()).pathname, `/u/${owner}/wishlist/${id}`)
 await page.goBack()
 await card.press('Enter')
 await page.waitForURL(`${origin}/u/${owner}/wishlist/${id}`)
 await page.goto(`${origin}/u/old_user/wishlist/${id}/${token}`)
 await page.getByRole('heading', { name: 'Birthday', exact: true }).waitFor()
 assert.equal(new URL(page.url()).pathname, `/u/${owner}/wishlist/${id}/${token}`)
 await page.goto(`${origin}/u/${owner}/wishlist/${id}/${nextToken}`)
 await page.getByRole('heading', { name: texts['lists.sharedUnavailable'], exact: true }).waitFor()
 await page.goto(`${origin}/u/${owner}/wishlist/${id}/invalid`)
 await page.getByRole('heading', { name: texts['lists.sharedUnavailable'], exact: true }).waitFor()
 assert.deepEqual(errors, [])
 console.log('Passed: public and link-only URLs, guest access, redirects and invalid tokens.')
} finally { await context.close(); await browser.close() }
